def next_confession() -> str:
    """Собирает признание из трёх кусочков и следит, чтобы оно не повторялось."""
    for _ in range(50):
        text = f"{random.choice(CONFESSION_OPEN)} {random.choice(CONFESSION_BODY)}.\n{random.choice(CONFESSION_CLOSE)}"
        if text not in _recent_confessions:
            _recent_confessions.append(text)
            if len(_recent_confessions) > _RECENT_LIMIT:
                _recent_confessions.pop(0)
            return text
    # Если 50 попыток не помогли — отдаём что есть
    return f"{random.choice(CONFESSION_OPEN)} {random.choice(CONFESSION_BODY)}.\n{random.choice(CONFESSION_CLOSE)}"


