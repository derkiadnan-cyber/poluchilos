# Память последних признаний, чтобы генератор не выдавал одно и то же подряд
_recent_confessions = []
_RECENT_LIMIT = 250


class Deck:
    """
    Колода без повторов: элементы перемешиваются и выдаются по одному.
    Когда колода кончается — перемешивается заново, но последняя карта
    прошлого круга не выпадет первой, чтобы не было ощущения повтора.
    """

    def __init__(self, items):
        self._items = list(items)
        if not self._items:
            raise ValueError("Deck: пустой список элементов")
        self._order = []
        self._last = None

    def next(self):
        if not self._order:
            self._order = self._items[:]
            random.shuffle(self._order)
            if len(self._order) > 1 and self._order[-1] == self._last:
                # последняя карта прошлого круга - не первой
                self._order.insert(random.randint(1, len(self._order) - 1), self._order.pop())
        item = self._order.pop()
        self._last = item
        return item


